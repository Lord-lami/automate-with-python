print("This program calculates the Area and Perimeter of a Rectangle")

length = float(input("What is the Length of the Rectangle? "))
breath = float(input("What is the Breath of the Rectangle? "))
print("The Area of the", length, "by", breath, "Rectangle is ", length * breath)
print("The Perimeter of the", length, "by", breath, "Rectangle is ", 2 * (length + breath))